param([string]$Executable = 'E:\Cricket07\Cricket07.exe')
$ErrorActionPreference = 'Stop'
$referenceHash = 'D776DBA0CC506B968F7D228E036CF42AEB4ABE45A8D1AD0D7226CDEBF91553A2'
if ((Get-FileHash -LiteralPath $Executable -Algorithm SHA256).Hash -ne $referenceHash) {
    throw 'Generate compatibility signatures only from the verified reference EXE.'
}
$bytes = [IO.File]::ReadAllBytes($Executable)
$pe = [BitConverter]::ToInt32($bytes,60)
$optional = $pe+24
$sections = @()
$sectionTable = $optional+[BitConverter]::ToUInt16($bytes,$pe+20)
for ($i=0; $i -lt [BitConverter]::ToUInt16($bytes,$pe+6); ++$i) {
    $p=$sectionTable+40*$i
    $sections += [PSCustomObject]@{ RVA=[BitConverter]::ToUInt32($bytes,$p+12); Raw=[BitConverter]::ToUInt32($bytes,$p+20); Size=[BitConverter]::ToUInt32($bytes,$p+16) }
}
$wanted=@(0x40bad0,0x413400,0x414950,0x417330,0x487c10,0x487c30,0x4d8f10,0x4da740,0x4e04b0,0x4e0550,0x4758c0,0x4758e0,0x6e5bd0,0x749001,0x74919b)
$metadata = Get-Content -LiteralPath (Join-Path $PSScriptRoot '../../work/functions.json') -Raw | ConvertFrom-Json
$functions = @($metadata.functions | Where-Object entry -in $wanted | Sort-Object entry)
if ($functions.Count -ne $wanted.Count) { throw 'Reference function metadata is incomplete.' }
$out = [Collections.Generic.List[string]]::new()
$out.Add('/* Generated by generate-compatibility.ps1 from reference EXE SHA-256:')
$out.Add(' * d776dba0cc506b968f7d228e036cf42aeb4abe45a8d1ad0d7226cdebf91553a2.')
$out.Add(' * Ranges are exclusive-end Ghidra function bodies from work/functions.json. */')
$out.Add('#ifndef C07_COMPATIBILITY_DATA_H')
$out.Add('#define C07_COMPATIBILITY_DATA_H')
$out.Add('typedef struct C07CodeRange { uint32_t va, rva; size_t length; const BYTE *bytes; } C07CodeRange;')
$ranges = [Collections.Generic.List[string]]::new()
$n=0
foreach($function in $functions) {
    foreach($range in $function.ranges) {
        $rva=[uint32]($range[0]-0x400000); $length=[int]($range[1]-$range[0])
        $section=@($sections | Where-Object { $rva -ge $_.RVA -and $rva+$length -le $_.RVA+$_.Size })
        if($section.Count -ne 1) { throw 'Function body is not contiguous file-backed bytes.' }
        $offset=[int]($section[0].Raw+$rva-$section[0].RVA)
        $out.Add(('static const BYTE c07_code_{0}[] = {{' -f $n))
        for($j=0; $j -lt $length; $j+=16) {
            $line = for($k=$j; $k -lt [Math]::Min($j+16,$length); ++$k) { '0x{0:x2}' -f $bytes[$offset+$k] }
            $out.Add('    '+($line -join ',')+',')
        }
        $out.Add('};')
        $ranges.Add(('    {{0x{0:x8}u,0x{1:x8}u,sizeof(c07_code_{2}),c07_code_{2}}},' -f $function.entry,$rva,$n))
        ++$n
    }
}
$out.Add('static const C07CodeRange c07_code_ranges[] = {')
foreach($line in $ranges) { $out.Add($line) }
$out.Add('};')
$out.Add('#endif')
[IO.File]::WriteAllLines((Join-Path $PSScriptRoot 'src/compatibility_data.h'),$out)
Write-Output ('Generated '+$functions.Count+' function signatures in '+$n+' body ranges.')
